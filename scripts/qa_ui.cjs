const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const http = require('node:http');
const { app, BrowserWindow, clipboard } = require('electron');
process.env.CHATSCOPE_QA = '1';
process.env.CHATSCOPE_DATA = path.join(__dirname, 'qa-ui-data');
process.env.CHATSCOPE_RUNTIME = path.join(__dirname, 'runtime');
require('./chatscope-src/main.cjs');
const delay = ms => new Promise(r => setTimeout(r, ms));
let server;
app.whenReady().then(async () => {
  const window = BrowserWindow.getAllWindows()[0];
  const run = code => window.webContents.executeJavaScript(code);
  const until = async condition => { for (let i=0;i<100;i++) { if (await run(condition)) return; await delay(150); } throw Error('UI timed out: '+condition); };
  await until("!!document.getElementById('demo') && !document.getElementById('welcome-status').textContent.includes('准备')");
  await run("document.getElementById('demo').click()");
  await until("document.getElementById('metric-total').textContent==='912'");
  assert.equal(await run("document.getElementById('metric-members').textContent"), '4');
  assert.equal(await run("document.querySelectorAll('.session').length"), 2);
  await delay(300);
  fs.writeFileSync(path.join(__dirname, '..', 'outputs', 'ChatScope-preview.png'), (await window.webContents.capturePage()).toPNG());
  server = http.createServer(async (req,res) => {
    let body=''; for await(const c of req) body+=c;
    const data=JSON.parse(body);
    const sample=JSON.parse(data.messages.find(m=>m.content?.includes('最近消息样本')).content.split('最近消息样本（不是全部记录）：')[1]);
    res.writeHead(200, {'Content-Type':'application/json'});
    const content = `## 聊天要点\n\n这段示例群聊主要围绕 **产品评审、界面设计和导入流程** 展开。[#${sample[0].id}]\n\n| 主题 | 建议 |\n| --- | --- |\n| 问题清单 | 确认负责人 |\n| 导入流程 | 核对进度 |\n\n### 下一步\n\n- [ ] 整理近期约定\n- [x] 找到原文依据\n\n> 这是根据近期样本整理的示例回答。\n\n\`\`\`javascript\nconst todo = ['核对问题清单'];\n// 引用示例 [#${sample[0].id}]\n\`\`\`\n\n[查看 Markdown 文档](https://marked.js.org/)`;
    res.end(JSON.stringify({choices:[{message:{role:'assistant',content}}]}));
  });
  await new Promise(r=>server.listen(0,'127.0.0.1',r));
  await run(`document.getElementById('settings').click(); document.getElementById('endpoint').value='http://127.0.0.1:${server.address().port}/v1'; document.getElementById('model').value='本地测试模型'; document.getElementById('save-settings').click()`);
  await until("!document.getElementById('settings-dialog').open");
  await run("document.getElementById('clear-chat').click()");
  await run("document.getElementById('question').value='有哪些重要的事？';document.getElementById('send').click()");
  await until("document.querySelectorAll('.turn.assistant .citation').length>0");
  assert.equal(await run("document.querySelector('.markdown-body h2').textContent"), '聊天要点');
  assert.ok(await run("document.querySelector('.markdown-body strong') && document.querySelector('.markdown-body table tbody tr') && document.querySelector('.markdown-body ul li') && document.querySelector('.markdown-body blockquote')"));
  assert.equal(await run("document.querySelectorAll('.markdown-body .citation').length"), 1);
  assert.ok(await run("document.querySelector('.markdown-body pre code').textContent.includes('[#')"));
  await run("document.querySelector('.code-toolbar button').click()");
  await delay(120); assert.ok(clipboard.readText().includes("const todo = ['核对问题清单'];"));
  const safety = await run(`(() => {let opened=''; const root=renderChatMarkdown('# Hello\\n\\n<script>window.__xss=true</script>\\n\\n<img src=x onerror=alert(1)>\\n\\n[x](javascript:alert(1))\\n\\n[local](file:///C:/secret)\\n\\n[valid](https://example.com/)\\n\\n<iframe src=https://example.com></iframe>', [], {cite(){},copy:async()=>{},openExternal:u=>{opened=u}}); const bad=root.querySelector('script,img,iframe,svg,object,embed,[onerror],[onclick]'); const links=[...root.querySelectorAll('a')]; links[0].click(); return {safe:!bad,count:links.length,opened};})()`);
  assert.deepEqual(safety, { safe:true, count:1, opened:'https://example.com/' });
  await delay(250);
  await run("document.getElementById('ai-conversation').scrollTop=0;document.getElementById('toast').classList.add('hidden')");
  await delay(180);
  fs.writeFileSync(path.join(__dirname, '..', 'outputs', 'ChatScope-question-preview.png'), (await window.webContents.capturePage()).toPNG());
  await run("document.querySelector('.citation').click()");
  await until("document.getElementById('evidence-dialog').open");
  assert.ok(await run("document.querySelectorAll('#evidence-content .message-row').length>0"));
  await run("document.querySelector('#evidence-dialog .close-dialog').click();document.getElementById('message-search').value='待办';document.getElementById('search-messages').click()");
  await delay(500);
  assert.ok(await run("[...document.querySelectorAll('#messages .message-row p')].every(p=>p.textContent.includes('待办'))"));
  fs.writeFileSync(path.join(__dirname, 'ui-test-result.json'), JSON.stringify({passed:true,statistics:912,members:4,model:'local mock only',citations:true,search:true,markdown:{headings:true,emphasis:true,tables:true,lists:true,quotes:true,code:true,copy:true,links:true,unsafeHtmlRemoved:true,codeCitationsPreserved:true}}));
  console.log('PASS: real Electron UI, Markdown formatting, code copy, safe links, HTML/script rejection, evidence dialog, search and screenshots');
}).catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>{server?.close();app.quit();});
